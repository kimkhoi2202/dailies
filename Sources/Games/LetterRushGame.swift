// MARK: - Model

final class LetterRushModel {
    enum Stage { case playing, ending, finished }

    /// What happened since the last frame, for haptics. Oldest first.
    enum Event {
        case join
        case back
        case scored(Int)
        case rejected
        case rivalWord
        case tick
        case over
    }

    struct Found {
        let word: String
        let points: Int
    }

    struct RivalBeat {
        let word: String
        let at: Double
    }

    static let roundLength = 80.0
    static let endLength = 1.9
    static let shakeLength = 0.35

    let letters: [Character]
    /// Every word the game knows on this board, longest first.
    let allWords: [String]
    let rivalName: String?
    let roundLength: Double

    private(set) var stage = Stage.playing
    /// The round clock.
    private(set) var time = 0.0
    /// Runs whenever the game is not paused, through the ending too.
    private(set) var ambient = 0.0
    private(set) var endClock = 0.0

    private(set) var path: [Int] = []
    /// The ambient time each tile joined the path. -100 when it is not in the path.
    private(set) var joinedAt: [Double] = Array(repeating: -100, count: 16)
    private(set) var word = ""
    private(set) var wordState = LetterRushWordState.empty

    private(set) var score = 0
    private(set) var shownScore = 0.0
    private(set) var found: [Found] = []
    private var foundSet = Set<String>()

    private(set) var rivalScore = 0
    private(set) var rivalWords: [String] = []
    private var rivalSet = Set<String>()
    private var rivalPlan: [RivalBeat] = []
    private var rivalNext = 0
    private(set) var rivalFoundAt = -100.0

    private(set) var pops: [LetterRushPop] = []
    private(set) var sparks: [LetterRushSpark] = []
    private(set) var rejectedWord = ""
    private(set) var rejectedAt = -100.0
    private(set) var praise: String? = nil
    private(set) var praiseAt = -100.0
    private var lastTick = -1
    private var events: [Event] = []

    /// rivalPace above 1 makes the other player find more words, for recordings that must be lost.
    init(options: GameOptions, roundLength: Double, rivalPace: Double) {
        self.roundLength = roundLength
        let rolled = LetterRushWords.board(seed: options.seed)
        letters = rolled.letters
        allWords = rolled.words
        var name: String? = nil
        if !options.solo {
            name = options.friendNames.first { !$0.isEmpty }
        }
        rivalName = name
        path.reserveCapacity(16)
        pops.reserveCapacity(6)
        sparks.reserveCapacity(32)
        events.reserveCapacity(8)
        guard name != nil, !rolled.words.isEmpty else { return }

        // The other player's round is planned ahead: which words, and when.
        var rng = LetterRushRandom(seed: options.seed, salt: LetterRushRandom.rival)
        let count = Swift.max(3, Int(Double(rng.int(7...11)) * roundLength / 80 * rivalPace))
        let short = allWords.filter { $0.count <= 4 }
        let mid = allWords.filter { $0.count == 5 }
        let long = allWords.filter { $0.count >= 6 }
        var taken = Set<String>()
        var picked: [String] = []
        for _ in 0..<count {
            let roll = rng.next()
            var pool: [String]
            if rivalPace > 1 {
                pool = roll < 0.6 ? mid : long
            } else {
                pool = roll < 0.55 ? short : (roll < 0.85 ? mid : long)
            }
            if pool.isEmpty { pool = allWords }
            var choice = pool[rng.index(pool.count)]
            var tries = 0
            while taken.contains(choice) && tries < 8 {
                choice = pool[rng.index(pool.count)]
                tries += 1
            }
            if taken.contains(choice) { continue }
            taken.insert(choice)
            picked.append(choice)
        }
        var times: [Double] = []
        let earliest = rivalPace > 1 ? 1.0 : 2.5
        for _ in picked.indices { times.append(rng.range(earliest, Swift.max(earliest + 1, roundLength - 1.5))) }
        times.sort()
        for (k, word) in picked.enumerated() { rivalPlan.append(RivalBeat(word: word, at: times[k])) }
    }

    // MARK: Reading

    var timeLeft: Double { Swift.max(0, roundLength - time) }

    func hasFound(_ word: String) -> Bool { foundSet.contains(word) }

    /// The best word on the board that neither player found.
    var missedWord: String? {
        allWords.first { !foundSet.contains($0) && !rivalSet.contains($0) }
    }

    var result: GameResult {
        let detail: String
        if found.isEmpty {
            detail = "No words this time"
        } else if let missed = missedWord, missed.count >= 5 {
            detail = "\(found.count) words. Nobody found \(missed)"
        } else {
            let best = found.max { $0.points < $1.points }?.word ?? found[0].word
            detail = "\(found.count) words, best \(best)"
        }
        guard rivalName != nil else { return GameResult(score: score, unit: "points", detail: detail) }
        return GameResult(score: score, unit: "points", detail: detail,
                          placement: score >= rivalScore ? 1 : 2, playerCount: 2)
    }

    /// Hands over the events owed since the last call.
    func takeEvents() -> [Event] {
        let owed = events
        events.removeAll(keepingCapacity: true)
        return owed
    }

    // MARK: Input

    /// A finger lands on a tile.
    func press(_ cell: Int) {
        guard stage == .playing, cell >= 0, cell < 16 else { return }
        clearPath()
        path.append(cell)
        joinedAt[cell] = ambient
        refreshWord()
        events.append(.join)
    }

    /// The finger slides over a tile. Sliding back onto the tile before the last one lets the last one go.
    func move(to cell: Int) {
        guard stage == .playing, !path.isEmpty, cell >= 0, cell < 16 else { return }
        let last = path[path.count - 1]
        if cell == last { return }
        if path.count >= 2, cell == path[path.count - 2] {
            joinedAt[last] = -100
            path.removeLast()
            refreshWord()
            events.append(.back)
            return
        }
        if path.contains(cell) { return }
        let dr = abs(cell / 4 - last / 4)
        let dc = abs(cell % 4 - last % 4)
        guard dr <= 1, dc <= 1 else { return }
        path.append(cell)
        joinedAt[cell] = ambient
        refreshWord()
        events.append(.join)
    }

    /// The finger lifts: the word is submitted.
    func release() {
        guard stage == .playing, !path.isEmpty else { return }
        let last = path[path.count - 1]
        switch wordState {
        case .valid(let points):
            score += points
            found.append(Found(word: word, points: points))
            foundSet.insert(word)
            if pops.count >= 6 { pops.removeFirst() }
            pops.append(LetterRushPop(text: "+\(points)", cell: last, age: 0, big: word.count >= 5))
            if word.count >= 5 {
                praise = word.count >= 7 ? "Perfect" : (word.count == 6 ? "Great" : "Nice")
                praiseAt = ambient
                if sparks.count > 20 { sparks.removeFirst(sparks.count - 20) }
                for n in 0..<12 {
                    sparks.append(LetterRushSpark(cell: last, angle: Double(n) / 12 * .pi * 2 + 0.2,
                                                  speed: 34 + Double(n % 3) * 13, age: 0))
                }
            }
            events.append(.scored(word.count))
        case .unknown:
            rejectedWord = word
            rejectedAt = ambient
            events.append(.rejected)
        case .found:
            rejectedWord = word
            rejectedAt = ambient
        case .short, .empty:
            break
        }
        clearPath()
    }

    /// The path is dropped without being submitted, as when the app pauses the game mid-drag.
    func cancel() {
        clearPath()
    }

    private func clearPath() {
        for cell in path { joinedAt[cell] = -100 }
        path.removeAll(keepingCapacity: true)
        word = ""
        wordState = .empty
    }

    private func refreshWord() {
        var spelled = ""
        for cell in path { spelled.append(letters[cell]) }
        word = spelled
        if path.count < 3 {
            wordState = .short
        } else if foundSet.contains(spelled) {
            wordState = .found
        } else if LetterRushWords.accepts(spelled) {
            wordState = .valid(LetterRushWords.points(spelled.count))
        } else {
            wordState = .unknown
        }
    }

    // MARK: Clock

    func step(dt raw: Double) {
        let dt = Swift.min(Swift.max(raw, 0), 1.0 / 30)
        if dt <= 0 { return }
        ambient += dt
        if stage == .finished { return }

        shownScore += (Double(score) - shownScore) * (1 - exp(-9 * dt))
        if abs(Double(score) - shownScore) < 0.6 { shownScore = Double(score) }
        if !pops.isEmpty {
            for k in pops.indices { pops[k].age += dt }
            pops.removeAll { $0.age >= 1 }
        }
        if !sparks.isEmpty {
            for k in sparks.indices { sparks[k].age += dt }
            sparks.removeAll { $0.age >= 0.75 }
        }

        switch stage {
        case .playing:
            time += dt
            while rivalNext < rivalPlan.count, rivalPlan[rivalNext].at <= time {
                let beat = rivalPlan[rivalNext]
                rivalNext += 1
                if rivalSet.contains(beat.word) { continue }
                rivalSet.insert(beat.word)
                rivalWords.append(beat.word)
                rivalScore += LetterRushWords.points(beat.word.count)
                rivalFoundAt = ambient
                events.append(.rivalWord)
            }
            let whole = Int(ceil(timeLeft))
            if whole <= 5, whole != lastTick, whole > 0 {
                lastTick = whole
                events.append(.tick)
            }
            if time >= roundLength {
                clearPath()
                stage = .ending
                endClock = 0
                events.append(.over)
            }
        case .ending:
            endClock += dt
            if endClock >= Self.endLength { stage = .finished }
        case .finished:
            break
        }
    }
}

// MARK: - Drawing

/// Paints the model as it is right now.
struct LetterRushCanvas: View {
    let model: LetterRushModel
    /// A new number every frame. The model is a class, so this is what makes SwiftUI repaint.
    var frame = 0

    var body: some View {
        Canvas(opaque: true, colorMode: .nonLinear, rendersAsynchronously: false) { context, size in
            if size.width <= 8 || size.height <= 8 { return }
            LetterRushCanvas.paint(model, &context, size)
        }
    }

    static func paint(_ model: LetterRushModel, _ ctx: inout GraphicsContext, _ size: CGSize) {
        var frame = LetterRushFrame()
        frame.letters = model.letters
        frame.path = model.path
        for cell in 0..<16 {
            let joined = model.joinedAt[cell]
            frame.joinAge[cell] = joined < 0 ? 10 : Swift.min(9, model.ambient - joined)
        }
        frame.word = model.word
        frame.wordState = model.wordState
        let sinceReject = model.ambient - model.rejectedAt
        if model.path.isEmpty, sinceReject < LetterRushModel.shakeLength {
            frame.word = model.rejectedWord
            frame.wordState = model.hasFound(model.rejectedWord) ? .found : .unknown
            frame.shakeAge = sinceReject
        }
        frame.score = model.score
        frame.shownScore = model.shownScore
        frame.wordCount = model.found.count
        frame.timeLeft = model.timeLeft
        frame.rivalName = model.rivalName
        frame.rivalScore = model.rivalScore
        frame.rivalWords = model.rivalWords.count
        frame.rivalAge = model.ambient - model.rivalFoundAt
        frame.pops = model.pops
        frame.sparks = model.sparks
        if !model.found.isEmpty {
            let tail = model.found.suffix(6)
            frame.recent.reserveCapacity(tail.count)
            for item in tail { frame.recent.append(item.word) }
        }
        frame.praise = model.praise
        frame.praiseAge = model.ambient - model.praiseAt
        frame.ambient = model.ambient
        frame.hintAlpha = 1
        if model.stage != .playing {
            frame.banner = "Time"
            frame.bannerAge = model.endClock
        }
        LetterRushPainter(size: size, frame: frame, showHUD: true).draw(&ctx)
    }
}

