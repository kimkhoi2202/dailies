// Letter Rush, playable.
//
// LetterRushWords   the word list, the spell check and the board solver.
// LetterRushModel   the rules of a round in plain Swift: step(dt:), press(_:), move(to:), release().
// LetterRushCanvas  paints one frame of the model with the clip's painter.
// LetterRushPilot   the scripted player. It only runs while GameDemo.autopilot is on.
// LetterRushRunner  keeps the clock, turns touches into tiles, fires haptics, reports the result.
// LetterRushGame    the view the app shows.

// MARK: - Words

enum LetterRushWords {
    /// Common English words of three to eight letters, in upper case. The other player's words and
    /// the best word nobody found come from here.
    static let list: [String] = {
        var out: [String] = []
        out.reserveCapacity(5600)
        for piece in common.split(whereSeparator: { $0 == " " || $0 == "\n" }) {
            out.append(String(piece))
        }
        return out
    }()

    static let known: Set<String> = Set(list)

    /// Every start of every word, so the board solver stops early.
    static let prefixes: Set<String> = {
        var set = Set<String>()
        set.reserveCapacity(24000)
        for word in list {
            var start = ""
            for letter in word {
                start.append(letter)
                set.insert(start)
            }
        }
        return set
    }()

    /// The eight tiles around each tile.
    static let neighbors: [[Int]] = {
        var out: [[Int]] = []
        for cell in 0..<16 {
            var near: [Int] = []
            let row = cell / 4
            let column = cell % 4
            for dr in -1...1 {
                for dc in -1...1 {
                    if dr == 0 && dc == 0 { continue }
                    let r = row + dr
                    let c = column + dc
                    if r < 0 || r > 3 || c < 0 || c > 3 { continue }
                    near.append(r * 4 + c)
                }
            }
            out.append(near)
        }
        return out
    }()

    static func points(_ length: Int) -> Int { LetterRushClip.points(length) }

    /// Does the game take this word? Yes when it is in the list or spelled right in English.
    static func accepts(_ word: String) -> Bool {
        guard word.count >= 3 else { return false }
        if known.contains(word) { return true }
        #if canImport(UIKit) && !os(macOS)
        guard let english else { return false }
        let lower = word.lowercased()
        let wrong = speller.rangeOfMisspelledWord(in: lower, range: NSRange(location: 0, length: lower.utf16.count),
                                                  startingAt: 0, wrap: false, language: english)
        return wrong.location == NSNotFound
        #else
        return false
        #endif
    }

    #if canImport(UIKit) && !os(macOS)
    private static let speller = UITextChecker()
    private static let english: String? = {
        let languages = UITextChecker.availableLanguages
        for wanted in ["en_US", "en"] where languages.contains(wanted) { return wanted }
        return languages.first { $0.hasPrefix("en") }
    }()
    #endif

    /// Every word in the list that can be made on a board, longest first.
    static func solve(_ letters: [Character]) -> [String] {
        var found = Set<String>()
        var used = [Bool](repeating: false, count: 16)
        var word = ""
        for start in 0..<16 { walk(start, letters, &used, &word, &found) }
        return found.sorted { a, b in a.count != b.count ? a.count > b.count : a < b }
    }

    private static func walk(_ cell: Int, _ letters: [Character], _ used: inout [Bool], _ word: inout String,
                             _ found: inout Set<String>) {
        word.append(letters[cell])
        if prefixes.contains(word) {
            if word.count >= 3, known.contains(word) { found.insert(word) }
            if word.count < 8 {
                used[cell] = true
                for next in neighbors[cell] where !used[next] { walk(next, letters, &used, &word, &found) }
                used[cell] = false
            }
        }
        word.removeLast()
    }

    /// Tiles that spell the word on the board, in order, if there are any.
    static func path(for word: String, on letters: [Character]) -> [Int]? {
        let target = Array(word)
        guard target.count >= 1 else { return nil }
        var used = [Bool](repeating: false, count: 16)
        var route: [Int] = []
        for start in 0..<16 where letters[start] == target[0] {
            if trace(start, target, letters, &used, &route) { return route }
        }
        return nil
    }

    private static func trace(_ cell: Int, _ target: [Character], _ letters: [Character], _ used: inout [Bool],
                              _ route: inout [Int]) -> Bool {
        route.append(cell)
        if route.count == target.count { return true }
        used[cell] = true
        let wanted = target[route.count]
        for next in neighbors[cell] where !used[next] && letters[next] == wanted {
            if trace(next, target, letters, &used, &route) { return true }
        }
        used[cell] = false
        route.removeLast()
        return false
    }

    /// The faces of the sixteen dice a board is rolled from.
    static let dice: [String] = [
        "AAEEGN", "ABBJOO", "ACHOPS", "AFFKPS", "AOOTTW", "CIMOTU", "DEILRX", "DELRVY",
        "DISTTY", "EEGHNW", "EEINSU", "EHRTVW", "EIOSST", "ELRTTY", "HIMNLU", "HLNNRZ",
    ]

    /// Rolls boards until one has plenty of words in it. The same seed always gives the same board.
    static func board(seed: UInt64) -> (letters: [Character], words: [String]) {
        var rng = LetterRushRandom(seed: seed, salt: LetterRushRandom.board)
        var bestLetters: [Character] = Array(repeating: "A", count: 16)
        var bestWords: [String] = []
        var bestWorth = -1
        for _ in 0..<24 {
            var order = Array(0..<16)
            var last = 15
            while last > 0 {
                order.swapAt(last, rng.int(0...last))
                last -= 1
            }
            var letters: [Character] = []
            letters.reserveCapacity(16)
            for die in order {
                let faces = Array(dice[die])
                letters.append(faces[rng.index(faces.count)])
            }
            let words = solve(letters)
            let long = words.filter { $0.count >= 5 }.count
            let worth = words.count + 3 * long
            if worth > bestWorth {
                bestWorth = worth
                bestLetters = letters
                bestWords = words
            }
            if words.count >= 45 && long >= 6 { break }
        }
        return (bestLetters, bestWords)
    }

