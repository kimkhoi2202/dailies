/// Holds the round between frames. Nothing is published: the timeline repaints every frame anyway.
final class LetterRushRunner: ObservableObject {
    let model: LetterRushModel
    private let seed: UInt64
    private let losing: Bool
    private var lastDate: Date?
    private var frame = 0
    private var reported = false
    private var dragging = false
    /// Made the first time it is needed, which is only when GameDemo.autopilot is on.
    private var pilot: LetterRushPilot?

    init(options: GameOptions) {
        seed = options.seed
        // For a recording the round can be cut short, and the other player gets ahead.
        let demo = GameDemo.autopilot
        let lose = demo && GameDemo.loseAfter != nil
        var length = LetterRushModel.roundLength
        if demo, let after = GameDemo.loseAfter { length = Swift.min(Swift.max(after, 4), LetterRushModel.roundLength) }
        losing = lose
        model = LetterRushModel(options: options, roundLength: length, rivalPace: lose ? 2.6 : 1)
    }

    /// Brings the model up to the given date. Returns a number that changes when there is a new frame to paint.
    func advance(to date: Date, link: GameLink) -> Int {
        if link.paused {
            lastDate = nil
            if dragging || !model.path.isEmpty {
                dragging = false
                model.cancel()
            }
            return frame
        }
        defer { lastDate = date }
        guard let before = lastDate else { return frame }
        var owed = Swift.min(Swift.max(date.timeIntervalSince(before), 0), 0.1)
        if owed <= 0 { return frame }
        while owed > 1e-6 {
            let dt = Swift.min(owed, 1.0 / 60)
            owed -= dt
            model.step(dt: dt)
            if GameDemo.autopilot {
                if pilot == nil { pilot = LetterRushPilot(seed: seed, slow: losing) }
                pilot?.play(model, dt: dt)
            }
        }
        settle(link)
        frame &+= 1
        return frame
    }

    /// A finger is on the screen at this point.
    func drag(at point: CGPoint, in size: CGSize, link: GameLink) {
        if link.paused || link.isFinished { return }
        let layout = LetterRushLayout(size: size, showHUD: true)
        if !dragging || model.path.isEmpty {
            dragging = true
            if let cell = layout.cell(at: point, loose: true) { model.press(cell) }
        } else if let cell = layout.cell(at: point, loose: false) {
            model.move(to: cell)
        }
        settle(link)
    }

    /// The finger lifted.
    func lift(link: GameLink) {
        dragging = false
        if link.paused || link.isFinished {
            model.cancel()
            return
        }
        model.release()
        settle(link)
    }

    /// Plays the haptics the model owes and reports the round once it is over.
    private func settle(_ link: GameLink) {
        for event in model.takeEvents() {
            switch event {
            case .join, .back, .tick: GameHaptics.tap()
            case .scored(let length): if length >= 5 { GameHaptics.success() } else { GameHaptics.thud() }
            case .rejected: GameHaptics.thud()
            case .rivalWord: break
            case .over:
                if model.rivalName != nil, model.score < model.rivalScore { GameHaptics.fail() } else { GameHaptics.success() }
            }
        }
        if model.stage == .finished, !reported {
            reported = true
            let result = model.result
            DispatchQueue.main.async { link.finish(result) }
        }
    }
}

public struct LetterRushGame: View {
    private let options: GameOptions
    private let link: GameLink

    public init(options: GameOptions, link: GameLink) {
        self.options = options
        self.link = link
    }

    public var body: some View {
        // A new link is a new round, so the round's state lives and dies with the link.
        LetterRushRound(options: options, link: link)
            .id(ObjectIdentifier(link))
    }
}

private struct LetterRushRound: View {
    @ObservedObject var link: GameLink
    @StateObject private var runner: LetterRushRunner

    init(options: GameOptions, link: GameLink) {
        self.link = link
        _runner = StateObject(wrappedValue: LetterRushRunner(options: options))
    }

    var body: some View {
        GeometryReader { geo in
            TimelineView(.animation(minimumInterval: nil, paused: link.paused)) { timeline in
                LetterRushCanvas(model: runner.model, frame: runner.advance(to: timeline.date, link: link))
            }
            .contentShape(Rectangle())
            .gesture(
                DragGesture(minimumDistance: 0, coordinateSpace: .local)
                    .onChanged { value in runner.drag(at: value.location, in: geo.size, link: link) }
                    .onEnded { _ in runner.lift(link: link) }
            )
        }
        .ignoresSafeArea()
        .accessibilityElement()
        .accessibilityLabel("Letter Rush. Drag through touching letters to make words.")
        .accessibilityAddTraits(.allowsDirectInteraction)
    }
}
