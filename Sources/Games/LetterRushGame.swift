/// Plays the round for recordings while GameDemo.autopilot is on. It drags real words from the
/// board at a person's pace, slips now and then, and plays slowly when the recording must be lost.
struct LetterRushPilot {
    private var rng: LetterRushRandom
    private let slow: Bool
    private var route: [Int] = []
    private var cursor = 0
    private var wait = 0.9
    private var sinceSlip = 0

    init(seed: UInt64, slow: Bool) {
        rng = LetterRushRandom(seed: seed, salt: LetterRushRandom.pilot)
        self.slow = slow
    }

    /// Call once per step, after the model has moved.
    mutating func play(_ model: LetterRushModel, dt: Double) {
        guard model.stage == .playing else { return }
        wait -= dt
        if wait > 0 { return }

        if route.isEmpty {
            guard let next = chooseWord(model), let found = LetterRushWords.path(for: next, on: model.letters) else {
                wait = 0.3
                return
            }
            route = found
            cursor = 1
            model.press(route[0])
            wait = rng.range(0.16, 0.26)
            return
        }
        if cursor < route.count {
            model.move(to: route[cursor])
            cursor += 1
            wait = rng.range(0.12, 0.24)
            return
        }
        model.release()
        route.removeAll(keepingCapacity: true)
        wait = slow ? rng.range(2.0, 3.2) : rng.range(1.6, 3.2)
    }

    /// A word not found yet, mostly short ones, with a slip every so often: a word found already,
    /// or three letters that spell nothing.
    private mutating func chooseWord(_ model: LetterRushModel) -> String? {
        sinceSlip += 1
        if sinceSlip >= 5, rng.next() < 0.5 {
            sinceSlip = 0
            if !model.found.isEmpty, rng.next() < 0.5 {
                return model.found[rng.index(model.found.count)].word
            }
            let start = rng.index(16)
            let near = LetterRushWords.neighbors[start]
            let second = near[rng.index(near.count)]
            let nearer = LetterRushWords.neighbors[second].filter { $0 != start }
            let third = nearer[rng.index(nearer.count)]
            return String([model.letters[start], model.letters[second], model.letters[third]])
        }
        let roll = rng.next()
        let wanted: Int
        if slow {
            wanted = 3
        } else {
            wanted = roll < 0.3 ? 3 : (roll < 0.65 ? 4 : (roll < 0.88 ? 5 : 6))
        }
        var pool: [String] = []
        for word in model.allWords where !model.hasFound(word) {
            if word.count == wanted || (wanted >= 6 && word.count >= 6) { pool.append(word) }
        }
        if pool.isEmpty {
            for word in model.allWords where !model.hasFound(word) { pool.append(word) }
        }
        if pool.isEmpty { return nil }
        return pool[rng.index(pool.count)]
    }
}

