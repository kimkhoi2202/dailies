import { mkdirSync, readFileSync, readdirSync, existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const gamesDir = join(root, 'games');
const font = readFileSync(
  join(root, 'node_modules/@expo-google-fonts/big-shoulders/900Black/BigShoulders_900Black.ttf'),
).toString('base64');

const head = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover"><style>@font-face{font-family:"Big Shoulders";font-weight:900;src:url(data:font/ttf;base64,${font}) format("truetype")}html,body{margin:0;height:100%;background:#0E0E0F;overflow:hidden;touch-action:none;-webkit-user-select:none;user-select:none;-webkit-touch-callout:none;-webkit-tap-highlight-color:transparent}canvas{display:block;width:100vw;height:100vh;touch-action:none}</style></head><body><canvas id="c"></canvas>`;
const sdk = readFileSync(join(gamesDir, 'sdk.js'), 'utf8');
const slugs = readdirSync(gamesDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith('_') && existsSync(join(gamesDir, d.name, 'game.js')))
  .map((d) => d.name)
  .sort();

const sources = {};
for (const slug of slugs) sources[slug] = readFileSync(join(gamesDir, slug, 'game.js'), 'utf8');

const safe = (s) => s.replace(/<\/script/gi, '<\\/script');
mkdirSync(join(root, 'src/games'), { recursive: true });
writeFileSync(
  join(root, 'src/games/generated.ts'),
  `// Generated by scripts/build-games.mjs. Do not edit.
export const GAME_HEAD = ${JSON.stringify(head)};
export const GAME_SDK = ${JSON.stringify(safe(sdk))};
export const GAME_SOURCES: Record<string, string> = ${JSON.stringify(
    Object.fromEntries(slugs.map((s) => [s, safe(sources[s])])),
  )};
`,
);

const out = join(root, 'dist-games');
mkdirSync(out, { recursive: true });
for (const slug of slugs) {
  writeFileSync(
    join(out, `${slug}.html`),
    `${head}<script>${safe(sdk)}</script><script>${safe(sources[slug])}</script></body></html>`,
  );
}
writeFileSync(
  join(out, 'index.html'),
  `<!doctype html><meta charset="utf-8"><title>Dailies games</title><style>body{background:#151412;color:#F3F0E9;font:14px system-ui;margin:20px}.g{display:inline-block;margin:0 16px 24px 0;vertical-align:top}iframe{width:390px;height:844px;border:0;border-radius:36px;background:#000;display:block}a{color:#FFC531}</style>
<p>Play mode on the left, clip mode on the right. Messages from each game are logged to the console.</p>
${slugs
    .map(
      (s) =>
        `<div class="g"><p>${s} <a href="${s}.html">play</a> <a href="${s}.html?mode=clip">clip</a></p><iframe src="${s}.html"></iframe></div><div class="g"><p>${s} clip</p><iframe src="${s}.html?mode=clip"></iframe></div>`,
    )
    .join('\n')}
<script>addEventListener('message',e=>{try{const m=JSON.parse(e.data);if(m.type!=='input'&&m.type!=='score')console.log('[game]',e.data)}catch(_){}})</script>`,
);
console.log(`Built ${slugs.length} games: ${slugs.join(', ') || 'none'}`);
